// `yarn workspace web capture`: freezes the instruction bytes today's builders produce for the built-in and
// published transaction flows into src/__fixtures__/flows/baseline.ts. Run once, before the IDL rework;
// re-running later would capture the new code's bytes and defeat the baseline.
import fs from 'node:fs'
import path from 'node:path'
import LZString from 'lz-string'
import { it } from 'vitest'
import { EXAMPLE_FLOWS } from '@/constants/example-flows'
import { BASELINE_CASES, BASELINE_WALLET, FLOWS_DIR, loadCaseFlow } from '@/__fixtures__/flows/baseline-cases'
import { evaluateTodayChain } from '@/__fixtures__/flows/evaluate-today'

const EXAMPLES = { 'Solana transfer': 'example-4-transfer.json', 'Program execution': 'example-5-counter.json' }

// Opt-in so a plain `yarn workspace web capture` cannot overwrite a frozen fixture: PLGRND_CAPTURE=baseline.
it.skipIf(process.env.PLGRND_CAPTURE !== 'baseline')('captures the baseline', async () => {
  for (const [title, file] of Object.entries(EXAMPLES)) {
    const example = EXAMPLE_FLOWS.find((e) => e.title === title)!
    const json = LZString.decompressFromEncodedURIComponent(example.shareUrl.replace('#flow=', ''))
    fs.writeFileSync(path.join(FLOWS_DIR, file), JSON.stringify(JSON.parse(json), null, 2) + '\n')
  }

  const baseline: Record<string, unknown> = {}
  for (const c of BASELINE_CASES) baseline[c.name] = await evaluateTodayChain(loadCaseFlow(c), BASELINE_WALLET)

  const source = [
    '// Generated by scripts/capture-baseline.capture.ts from the pre-rework builders. Do not regenerate.',
    "import type { BaselineInstruction } from './baseline-types'",
    '',
    '/** Per case: one entry per transaction chain, each the ordered instructions it builds. */',
    `export const BASELINE: Record<string, BaselineInstruction[][]> = ${JSON.stringify(baseline, null, 2)}`,
    '',
  ].join('\n')
  fs.writeFileSync(path.join(FLOWS_DIR, 'baseline.ts'), source)
})
