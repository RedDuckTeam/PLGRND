// `yarn workspace web capture`: freezes what a version-3 flow can contain into src/constants/flow-v3-shape.ts — the
// node types, data keys and handle fields that PLGRND wrote before the IDL rework (2026-10-28) — so requiresV4 can
// tell old-shaped flows from flows only a newer widget understands. The registry handles are read before any node
// config changed; data keys also come from main's node data types and every published flow (scripts/.v3shape-input.json,
// generated from the main branch by scripts/derive-v3-shape-input.cjs). Do not regenerate.
import fs from 'node:fs'
import path from 'node:path'
import { it } from 'vitest'
import { INSTRUCTIONS } from '@/constants/solana/instructions-config'
import { nodeConfigRegistry } from '@/utils/node/node-config-registry'

interface ShapeInput {
  types: string[]
  dataKeys: Record<string, string[]>
  handles: Record<string, string[]>
}

// Handles created at runtime from user choices: IDL accounts/args, program-account fields, extra signers, PDA seeds.
const DYNAMIC_HANDLES: Record<string, string[]> = {
  PROGRAM_INSTRUCTIONS: ['account_*', 'arg_*'],
  PROGRAM_ACCOUNT: ['field_*'],
  TRANSACTION: ['signer_*'],
  PDA: ['seed#*'],
  INSTRUCTIONS: [...new Set(INSTRUCTIONS.flatMap((def) => def.fields.map((f) => f.key)))],
}

// Opt-in so a plain `yarn workspace web capture` cannot overwrite a frozen fixture: PLGRND_CAPTURE=v3-shape.
it.skipIf(process.env.PLGRND_CAPTURE !== 'v3-shape')('captures the v3 flow shape', () => {
  const input = JSON.parse(fs.readFileSync(path.join(__dirname, '.v3shape-input.json'), 'utf8')) as ShapeInput
  const registry = nodeConfigRegistry as Record<string, { handles: readonly { dataField: string }[] }>
  const shape: Record<string, { data: string[]; handles: string[] }> = {}
  for (const type of input.types) {
    const handles = new Set([
      ...(registry[type]?.handles ?? []).map((h) => h.dataField),
      ...(input.handles[type] ?? []),
      ...(DYNAMIC_HANDLES[type] ?? []),
    ])
    const data = new Set([...(input.dataKeys[type] ?? []), ...handles])
    shape[type] = { data: [...data].sort(), handles: [...handles].sort() }
  }
  const source = [
    '// Generated by scripts/capture-v3-shape.capture.ts from the pre-rework code and published flows. Do not regenerate.',
    '// A key ending in `*` matches any suffix.',
    '',
    `export const FLOW_V3_SHAPE: Readonly<Record<string, { data: readonly string[]; handles: readonly string[] }>> = ${JSON.stringify(shape, null, 2)}`,
    '',
  ].join('\n')
  fs.writeFileSync(path.join(__dirname, '../src/constants/flow-v3-shape.ts'), source)
})
